"""Execution Trace Report Generator for QuantTutorBench.

Produces a Markdown file containing the full conversation transcript
and complete (untruncated) agent tool-call trace for human review.

Scores are intentionally excluded — they live in the separate
score report generated by ``--save-scores``.

Usage:
    from evaluation.trace_report import generate_trace_md
    md = generate_trace_md(result, proxy_logs, agent_name=..., model=..., condition=...)
    Path("trace.md").write_text(md)
"""

import json as _json
from datetime import datetime

_NON_SUBSTANTIVE_TOOLS = frozenset({"send_message"})


def generate_trace_md(
    result,
    proxy_logs: list,
    *,
    agent_name: str = "",
    model: str = "",
    condition: str = "",
) -> str:
    """Generate a full execution trace Markdown report.

    Args:
        result: TaskResult object (from schemas.py).
        proxy_logs: List of ToolCallLog objects (from proxy.get_logs()).
        agent_name: Agent SDK identifier (e.g. "openai").
        model: Model name (e.g. "openai/gpt-5.2").
        condition: Test condition (e.g. "agent").

    Returns:
        Complete Markdown string (no truncation anywhere).
    """
    tid = getattr(result, "task_id", "unknown")
    pid = getattr(result, "persona_id", "unknown")
    ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    duration = getattr(result, "duration_seconds", 0.0)
    cost = getattr(result, "cost_usd", 0.0)

    lines: list[str] = []
    _a = lines.append

    # ── Header ──
    _a(f"# Trace: {tid} / {pid}\n")
    _a(f"Agent: {agent_name} | Model: {model} | Condition: {condition}")
    _a(f"Timestamp: {ts} | Duration: {duration:.1f}s | Cost: ${cost:.4f}\n")
    _a("---\n")

    # ── Conversation ──
    _a("## Conversation\n")
    turns = getattr(result, "turns", [])
    for i, turn in enumerate(turns, 1):
        role_label = "User" if turn.role == "user" else "Assistant"
        _a(f"### Turn {i} — {role_label}\n")
        _a(turn.content)
        _a("")

    _a("---\n")

    # ── Agent Trace ──
    _a("## Agent Trace\n")
    step = 0
    for log in proxy_logs:
        if log.name in _NON_SUBSTANTIVE_TOOLS:
            continue
        step += 1
        status = "OK" if log.success else "FAIL"
        duration_ms = getattr(log, "duration_ms", 0) or 0
        _a(f"### Step {step}: {log.name} [{status}] ({duration_ms:.0f}ms)\n")

        # Args
        _a("**Args:**")
        try:
            args_str = _json.dumps(log.args, indent=2, default=str, ensure_ascii=False)
        except (TypeError, ValueError):
            args_str = str(log.args)
        _a(f"```json\n{args_str}\n```\n")

        # Result (full, untruncated)
        _a("**Result:**")
        result_str = str(log.result) if log.result is not None else "(no output)"
        # Try to pretty-print JSON results
        if result_str.startswith("{") or result_str.startswith("["):
            try:
                parsed = _json.loads(result_str)
                result_str = _json.dumps(
                    parsed, indent=2, default=str, ensure_ascii=False
                )
                _a(f"```json\n{result_str}\n```\n")
            except (ValueError, TypeError):
                _a(f"```\n{result_str}\n```\n")
        else:
            _a(f"```\n{result_str}\n```\n")

    if step == 0:
        _a("_(no substantive tool calls)_\n")

    return "\n".join(lines)
