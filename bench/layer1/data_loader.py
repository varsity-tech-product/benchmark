"""Data loader for Layer 1 test items.

Loads QuantTutorTask objects from bench/tasks/layer1/{category}/*.json
(generated by the synthesis pipeline). Also provides backward-compatible
Layer1Item wrapper for the runner.

Design doc §5.0: Layer 1 (~2000 single-turn items via LLMTestCase + GEval).
"""

import json
import sys
from pathlib import Path
from typing import Optional

# Ensure bench/ is on the import path
BENCH_ROOT = Path(__file__).parent.parent
if str(BENCH_ROOT) not in sys.path:
    sys.path.insert(0, str(BENCH_ROOT))

from orchestrator.schemas import QuantTutorTask

# Default task directory: bench/tasks/layer1/
DEFAULT_TASK_ROOT = BENCH_ROOT / "tasks" / "layer1"

# Layer 1 category names (matches TaskCategory enum values)
LAYER1_CATEGORIES = [
    "conceptual_qa",
    "strategy_explanation",
    "code_generation",
    "code_debugging",
    "data_interpretation",
    "multi_step_reasoning",
]


class Layer1Item:
    """A single Layer 1 test item (backward-compatible wrapper).

    Wraps a QuantTutorTask with convenience accessors that match the
    fields expected by Layer1Runner.
    """

    def __init__(self, task: QuantTutorTask):
        self._task = task

    @property
    def item_id(self) -> str:
        return self._task.task_id

    @property
    def source_dataset(self) -> str:
        return self._task.source_dataset or ""

    @property
    def category(self) -> str:
        return self._task.category.value

    @property
    def difficulty(self) -> str:
        return self._task.difficulty.value

    @property
    def question(self) -> str:
        return self._task.description

    @property
    def reference_answer(self) -> str:
        return self._task.reference_answer or ""

    @property
    def synthetic_response(self) -> str:
        return self._task.synthetic_response or ""

    @property
    def context(self) -> Optional[str]:
        return self._task.context

    @property
    def tags(self) -> list[str]:
        return self._task.tags

    @property
    def task(self) -> QuantTutorTask:
        """Access the underlying QuantTutorTask."""
        return self._task

    def to_dict(self) -> dict:
        return {
            "item_id": self.item_id,
            "source_dataset": self.source_dataset,
            "category": self.category,
            "difficulty": self.difficulty,
            "question": self.question,
            "reference_answer": self.reference_answer,
            "synthetic_response": self.synthetic_response,
            "context": self.context,
            "tags": self.tags,
        }


def load_task_json(file_path: str | Path) -> QuantTutorTask:
    """Load a single QuantTutorTask from a JSON file."""
    with open(file_path) as f:
        data = json.load(f)
    return QuantTutorTask(**data)


def load_layer1_tasks(
    task_root: Optional[str | Path] = None,
    categories: Optional[list[str]] = None,
    max_items: Optional[int] = None,
) -> list[QuantTutorTask]:
    """Load Layer 1 QuantTutorTask objects from bench/tasks/layer1/.

    Scans all {category}/*.json files in the task directory.

    Args:
        task_root: Root directory containing category subdirectories.
        categories: Filter by categories (e.g., ['conceptual_qa', 'code_generation']).
        max_items: Maximum number of items to load.

    Returns:
        List of QuantTutorTask objects.
    """
    task_root = Path(task_root) if task_root else DEFAULT_TASK_ROOT
    tasks: list[QuantTutorTask] = []

    if not task_root.exists():
        print(f"Warning: task directory not found: {task_root}")
        return tasks

    target_categories = categories or LAYER1_CATEGORIES

    for cat in sorted(target_categories):
        cat_dir = task_root / cat
        if not cat_dir.exists():
            continue

        for json_file in sorted(cat_dir.glob("*.json")):
            task = load_task_json(json_file)
            tasks.append(task)

            if max_items and len(tasks) >= max_items:
                return tasks

    return tasks


def load_layer1_items(
    task_root: Optional[str | Path] = None,
    categories: Optional[list[str]] = None,
    max_items: Optional[int] = None,
) -> list[Layer1Item]:
    """Load Layer 1 items as Layer1Item wrappers (backward-compatible).

    Args:
        task_root: Root directory containing category subdirectories.
        categories: Filter by categories.
        max_items: Maximum number of items to load.

    Returns:
        List of Layer1Item wrapper objects.
    """
    tasks = load_layer1_tasks(
        task_root=task_root,
        categories=categories,
        max_items=max_items,
    )
    return [Layer1Item(t) for t in tasks]


def get_layer1_stats(items: list[Layer1Item]) -> dict:
    """Get statistics about loaded Layer 1 items."""
    by_category: dict[str, int] = {}
    by_difficulty: dict[str, int] = {}
    by_source: dict[str, int] = {}

    for item in items:
        by_category[item.category] = by_category.get(item.category, 0) + 1
        by_difficulty[item.difficulty] = by_difficulty.get(item.difficulty, 0) + 1
        by_source[item.source_dataset] = by_source.get(item.source_dataset, 0) + 1

    return {
        "total_items": len(items),
        "by_category": by_category,
        "by_difficulty": by_difficulty,
        "by_source": by_source,
    }
