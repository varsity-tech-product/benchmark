def _build_default_spec(
    name: str,
    raw_info: dict[str, Any],
    *,
    benchmark_role: BenchmarkRole,
) -> ToolSpec:
    """Build a safe default ToolSpec from the current raw tool definition."""
    family = _infer_family(name)
    params = raw_info.get("params", {})
    description = _sanitize_text(raw_info.get("description", f"Tool: {name}"))

    return ToolSpec(
        name=name,
        description=description,
        input_schema=normalize_input_schema(params),
        guidance=ToolGuidance(
            family=family,
            use_when=_default_use_when(family),
            avoid_when=_default_avoid_when(family),
            common_mistakes=_default_common_mistakes(name, params),
            returns=_default_returns(name, family),
            related_tools=_default_related_tools(name, family),
        ),
        examples=(),
        benchmark_role=benchmark_role,
        domain_scope=_infer_domain_scope(name, family),
        abstraction_level=_infer_abstraction_level(name),
    )


def _base_catalog() -> dict[str, ToolSpec]:
    """Build the full base catalog from current server tool definitions."""
    catalog: dict[str, ToolSpec] = {}

    for name, raw in CORE_TOOLS.items():
        catalog[name] = _build_default_spec(name, raw, benchmark_role="core")

    for name, raw in DISTRACTOR_TOOLS.items():
        catalog[name] = _build_default_spec(name, raw, benchmark_role="distractor")

    for name, spec in DRAFT_TOOL_SPECS.items():
        if name in catalog:
            # Preserve the runtime role from the base catalog; draft text stays authoritative.
            catalog[name] = replace(spec, benchmark_role=catalog[name].benchmark_role)
        else:
            catalog[name] = spec

    return catalog


BASE_TOOL_SPECS: dict[str, ToolSpec] = _base_catalog()


def get_canonical_tool_spec(name: str) -> ToolSpec:
    """Return a canonical ToolSpec by name."""
    return BASE_TOOL_SPECS[name]


def get_canonical_tool_specs(
    *,
    include_distractors: bool = True,
) -> dict[str, ToolSpec]:
    """Return the canonical server tool catalog.

    By default includes both current core tools and distractor tools.
    """
    if include_distractors:
        return dict(BASE_TOOL_SPECS)
    return {
        name: spec
        for name, spec in BASE_TOOL_SPECS.items()
        if spec.benchmark_role != "distractor"
    }


def get_task_tool_specs(
    *,
    core_tool_names: Iterable[str],
    convenient_tool_names: Iterable[str] = (),
    distractor_tool_names: Iterable[str] = (),
) -> dict[str, ToolSpec]:
    """Return task-specific ToolSpecs with internal role overlays.

    `convenient` remains an internal role only; the agent-visible payload
    strips it out later.
    """
    task_specs: dict[str, ToolSpec] = {}

    for name in core_tool_names:
        spec = BASE_TOOL_SPECS.get(name)
        if spec is None:
            continue
        task_specs[name] = replace(spec, benchmark_role="core")

    for name in convenient_tool_names:
        spec = BASE_TOOL_SPECS.get(name)
        if spec is None:
            continue
        task_specs[name] = replace(spec, benchmark_role="convenient")

    for name in distractor_tool_names:
        spec = BASE_TOOL_SPECS.get(name)
        if spec is None:
            continue
        task_specs[name] = replace(spec, benchmark_role="distractor")

    return task_specs


def get_agent_visible_tool_spec(name: str) -> dict[str, Any]:
    """Return the safe agent-visible payload for one canonical tool."""
    return agent_visible_payload(get_canonical_tool_spec(name))


def get_agent_visible_task_tool_specs(
    *,
    core_tool_names: Iterable[str],
    convenient_tool_names: Iterable[str] = (),
    distractor_tool_names: Iterable[str] = (),
) -> dict[str, dict[str, Any]]:
    """Return safe agent-visible task-specific tool payloads."""
    return {
        name: agent_visible_payload(spec)
        for name, spec in get_task_tool_specs(
            core_tool_names=core_tool_names,
            convenient_tool_names=convenient_tool_names,
            distractor_tool_names=distractor_tool_names,
        ).items()
    }
