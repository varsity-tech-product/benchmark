"""Execution Trace Report Generator for QuantTutorBench.

Produces a Markdown file containing the full conversation transcript
interleaved with agent tool-call traces, grouped by conversation turn.

Scores are intentionally excluded — they live in the separate
score report generated by ``--save-scores``.

Usage:
    from server.eval.reports.trace_report import generate_trace_md
    md = generate_trace_md(result, proxy_logs, agent_name=..., model=..., condition=...)
    Path("trace.md").write_text(md)
"""

import json as _json
from collections import defaultdict
from datetime import datetime

from server.tool_filters import NON_SUBSTANTIVE_TOOLS


def _format_tool_call(log, step: int) -> list[str]:
    """Format a single tool call log entry as Markdown lines."""
    lines: list[str] = []
    status = "OK" if log.success else "FAIL"
    duration_ms = getattr(log, "duration_ms", 0) or 0
    lines.append(f"#### Step {step}: {log.name} [{status}] ({duration_ms:.0f}ms)\n")

    # Args
    lines.append("**Args:**")
    try:
        args_str = _json.dumps(log.args, indent=2, default=str, ensure_ascii=False)
    except (TypeError, ValueError):
        args_str = str(log.args)
    lines.append(f"```json\n{args_str}\n```\n")

    # Result (full, untruncated)
    lines.append("**Result:**")
    result_str = str(log.result) if log.result is not None else "(no output)"
    if result_str.startswith("{") or result_str.startswith("["):
        try:
            parsed = _json.loads(result_str)
            result_str = _json.dumps(parsed, indent=2, default=str, ensure_ascii=False)
            lines.append(f"```json\n{result_str}\n```\n")
        except (ValueError, TypeError):
            lines.append(f"```\n{result_str}\n```\n")
    else:
        lines.append(f"```\n{result_str}\n```\n")

    return lines


def _format_thinking_block(entry: dict) -> list[str]:
    """Format a single thinking trace entry as a collapsible Markdown block."""
    lines: list[str] = []
    iteration = entry.get("iteration", "?")
    thinking = entry.get("thinking", "")
    token_estimate = len(thinking) // 4  # rough char→token estimate
    lines.append("")
    lines.append(
        f"<details><summary>Thinking (iteration {iteration}, "
        f"~{token_estimate} tokens)</summary>"
    )
    lines.append("")
    lines.append(thinking)
    lines.append("")
    lines.append("</details>")
    lines.append("")
    return lines


def generate_trace_md(
    result,
    proxy_logs: list,
    *,
    agent_name: str = "",
    model: str = "",
    condition: str = "",
    thinking_trace: list[dict] | None = None,
) -> str:
    """Generate a full execution trace Markdown report.

    Tool calls are grouped under the conversation turn in which they
    occurred, using the ``turn_index`` field from each ToolCallLog.
    Thinking (COT) blocks are interleaved before tool calls under the
    same turn, each wrapped in a collapsible ``<details>`` element.

    Args:
        result: TaskResult object (from schemas.py).
        proxy_logs: List of ToolCallLog objects (from proxy.get_logs()).
        agent_name: Agent SDK identifier (e.g. "openai").
        model: Model name (e.g. "openai/gpt-5.2").
        condition: Test condition (e.g. "agent").
        thinking_trace: List of thinking entries from adapter.get_thinking_trace().
            Each entry: {"turn_index": int, "iteration": int, "thinking": str}.

    Returns:
        Complete Markdown string (no truncation anywhere).
    """
    tid = getattr(result, "task_id", "unknown")
    pid = getattr(result, "persona_id", "unknown")
    ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    duration = getattr(result, "duration_seconds", 0.0)

    lines: list[str] = []
    _a = lines.append

    # ── Header ──
    _a(f"# Trace: {tid} / {pid}\n")
    _a(f"Agent: {agent_name} | Model: {model} | Condition: {condition}")
    _a(f"Timestamp: {ts} | Duration: {duration:.1f}s\n")

    _a("---\n")

    # ── Group tool calls by conversation-turn index ──
    # turn_index=N from the proxy means "tools called while responding to
    # user message N".  In the turns list the user message is at 2*N and
    # the assistant response is at 2*N+1.  We display tool calls under the
    # assistant (Tutor) turn that produced them.
    tools_by_turn: dict[int, list] = defaultdict(list)
    for log in proxy_logs:
        if log.name in NON_SUBSTANTIVE_TOOLS:
            continue
        raw_idx = getattr(log, "turn_index", 0)
        display_idx = raw_idx * 2 + 1  # attach to assistant turn
        tools_by_turn[display_idx].append(log)

    # ── Group thinking blocks by conversation-turn index ──
    # thinking_trace entries use turn_index=N matching the proxy convention.
    # Display under the assistant turn (2*N + 1), before tool calls.
    thinking_by_turn: dict[int, list[dict]] = defaultdict(list)
    for entry in thinking_trace or []:
        raw_idx = entry.get("turn_index", 0)
        display_idx = raw_idx * 2 + 1
        thinking_by_turn[display_idx].append(entry)

    # ── Interleaved Conversation + Thinking + Tool Calls ──
    _a("## Conversation & Agent Trace\n")
    turns = getattr(result, "turns", [])
    global_step = 0

    for i, turn in enumerate(turns):
        turn_num = i + 1
        role_label = "Student" if turn.role == "user" else "Tutor"
        _a(f"### Turn {turn_num} — {role_label}\n")
        _a(turn.content)
        _a("")

        # Thinking blocks (COT) — rendered before tool calls
        turn_thinking = thinking_by_turn.get(i, [])
        for entry in turn_thinking:
            lines.extend(_format_thinking_block(entry))

        # Tool calls that the agent made to produce this turn's response
        turn_tools = tools_by_turn.get(i, [])
        if turn_tools:
            # Blank line before <details> ensures Markdown renderers
            # treat the HTML block correctly.
            _a("")
            _a(f"<details><summary>Tool Calls ({len(turn_tools)} calls)</summary>")
            _a("")
            for log in turn_tools:
                global_step += 1
                lines.extend(_format_tool_call(log, global_step))
            _a("")
            _a("</details>")
            _a("")

    # ── Orphaned tool calls (turn_index doesn't match any conversation turn) ──
    all_matched = set()
    for i in range(len(turns)):
        all_matched.update(id(log) for log in tools_by_turn.get(i, []))

    orphaned = [
        log
        for log in proxy_logs
        if log.name not in NON_SUBSTANTIVE_TOOLS and id(log) not in all_matched
    ]
    if orphaned:
        _a("---\n")
        _a("## Unattributed Tool Calls\n")
        _a("_These tool calls could not be matched to a conversation turn._\n")
        for log in orphaned:
            global_step += 1
            lines.extend(_format_tool_call(log, global_step))

    if global_step == 0:
        _a("_(no substantive tool calls)_\n")

    return "\n".join(lines)
